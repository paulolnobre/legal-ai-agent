"""Generate the agent flow document from the compiled LangGraph source of truth.

The diagram is written, not drawn. LangGraph emits Mermaid for the graph it
actually compiled, so the picture cannot quietly disagree with the code: CI
regenerates this file and fails if the working tree differs.

Markdown rather than a bare `.mmd` because GitHub renders a fenced ```mermaid
block inline, which means the flow is readable where it lives, with no build
step, no renderer and nothing binary in the repository.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from core.services.legal_assistant.graph import _app  # noqa: E402

OUTPUT = Path(__file__).with_name("agent-flow.md")

_HEADER = """<!--
Generated by docs/architecture/agent_flow.py from the compiled LangGraph.
Do not edit by hand: CI regenerates this file and fails if it differs.
-->

# Agent flow

Every path a message can take through the graph, as compiled. `orchestrate`
routes; `cache_lookup` can end the run on a hit; `retrieve` reads the corpus as
bounded passages; the specialists answer and stop.

"""


def render() -> str:
    """The document, with exactly one trailing newline whatever LangGraph emits."""
    mermaid = _app.get_graph().draw_mermaid().rstrip("\n")
    return f"{_HEADER}```mermaid\n{mermaid}\n```\n"


def generate() -> None:
    OUTPUT.write_text(render(), encoding="utf-8")


if __name__ == "__main__":
    generate()
